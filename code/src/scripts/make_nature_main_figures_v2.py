def export_source_manifest(source_dir: Path, out_dir: Path) -> None:
    copied_dir = out_dir / "source_data"
    copied_dir.mkdir(parents=True, exist_ok=True)
    for path in sorted(source_dir.iterdir()):
        if path.is_file() and path.suffix.lower() in {".csv", ".json", ".md"}:
            shutil.copy2(path, copied_dir / path.name)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Create draft Nature-style GMNPS main figures from source data")
    parser.add_argument("--source-dir", default="outputs/nature_source_data_v2")
    parser.add_argument("--output-dir", default="outputs/nature_figures_v2")
    return parser


def main() -> None:
    args = build_parser().parse_args()
    source_dir = Path(args.source_dir)
    out_dir = Path(args.output_dir)
    set_style()
    figure_1_framework(source_dir, out_dir)
    figure_2_preservation(source_dir, out_dir)
    figure_3_heterogeneity(source_dir, out_dir)
    figure_4_validation(source_dir, out_dir)
    export_source_manifest(source_dir, out_dir)


if __name__ == "__main__":
    main()
